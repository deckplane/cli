// traefikImage needs v3.6 or newer: older releases cannot talk to Docker 29+.
const traefikImage = "traefik:v3.6"

// The compose file is regenerated on every install and update so fixes
// reach existing installs. People customise via compose.override.yaml,
// which Docker Compose merges automatically.
var composeTemplate = template.Must(template.New("compose").Parse(`# Generated by the Deckplane CLI. Do not edit: this file is rewritten by
# "deckplane core install" and "deckplane core update". Put your own changes
# in compose.override.yaml next to this file.
name: ` + projectName + `

services:
  postgres:
    image: postgres:16-alpine
    container_name: ` + dbContainer + `
    restart: unless-stopped
    environment:
      POSTGRES_USER: deckplane
      POSTGRES_PASSWORD: ${DB_PASSWORD:?DB_PASSWORD is missing from .env}
      POSTGRES_DB: deckplane
    volumes:
      - pgdata:/var/lib/postgresql/data
    networks:
      - internal
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U deckplane"]
      interval: 5s
      timeout: 5s
      retries: 10

  core:
    image: {{.Image}}
    container_name: ` + containerName + `
    restart: unless-stopped
    env_file: .env
    depends_on:
      postgres:
        condition: service_healthy
    healthcheck:
      test: ["CMD-SHELL", "bun -e \"fetch('http://localhost:3000/health').then(r=>{if(!r.ok)process.exit(1)}).catch(()=>process.exit(1))\""]
      interval: 5s
      timeout: 5s
      retries: 10
      start_period: 20s
    networks:
      - internal
      - traefik
    labels:
      - "traefik.enable=true"
      - "traefik.docker.network={{.TraefikNetwork}}"
{{- if .HTTPS}}
      - "traefik.http.routers.deckplane-core.rule=Host(` + "`{{.Domain}}`" + `)"
      - "traefik.http.routers.deckplane-core.entrypoints={{.Entrypoint}}"
      - "traefik.http.routers.deckplane-core.tls=true"
      - "traefik.http.routers.deckplane-core.tls.certresolver={{.CertResolver}}"
{{- else}}
      # No domain: answer every request on the server's address that no
      # other router claims (priority 1 is the lowest).
      - "traefik.http.routers.deckplane-core.rule=PathPrefix(` + "`/`" + `)"
      - "traefik.http.routers.deckplane-core.priority=1"
      - "traefik.http.routers.deckplane-core.entrypoints={{.HTTPEntrypoint}}"
{{- end}}
      - "traefik.http.services.deckplane-core.loadbalancer.server.port=3000"
      - "traefik.http.services.deckplane-core.loadbalancer.responseforwarding.flushinterval=0"
{{- if .Bundled}}

  # Reverse proxy in front of Core{{if .HTTPS}}, with free HTTPS certificates from Let's Encrypt{{end}}.
  traefik:
    image: ` + traefikImage + `
    container_name: ` + traefikName + `
    restart: unless-stopped
    command:
      - --providers.docker=true
      - --providers.docker.exposedbydefault=false
      - --entrypoints.web.address=:80
{{- if .HTTPS}}
      - --entrypoints.web.http.redirections.entrypoint.to=websecure
      - --entrypoints.web.http.redirections.entrypoint.scheme=https
      - --entrypoints.websecure.address=:443
      - --certificatesresolvers.le.acme.email={{.ACMEEmail}}
      - --certificatesresolvers.le.acme.storage=/letsencrypt/acme.json
      - --certificatesresolvers.le.acme.httpchallenge.entrypoint=web
{{- end}}
    ports:
      - "80:80"
{{- if .HTTPS}}
      - "443:443"
{{- end}}
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock:ro
      - letsencrypt:/letsencrypt
    networks:
      - traefik
{{- end}}

# Volume names are fixed so data survives the project rename from v0.1.0.
volumes:
  pgdata:
    name: ` + dbVolume + `
{{- if .Bundled}}
  letsencrypt:
    name: ` + certVolume + `
{{- end}}

networks:
  internal:
  traefik:
    name: {{.TraefikNetwork}}
{{- if not .Bundled}}
    external: true
{{- end}}
`))

// legacyComposeFiles are names Docker Compose also loads; the old CLI wrote
// docker-compose.yml. Leaving them next to compose.yaml makes Compose warn
// and could start the wrong stack, so they are moved aside.
var legacyComposeFiles = []string{"docker-compose.yml", "docker-compose.yaml", "compose.yml"}

// releaseLegacyContainers removes Core's own containers created under the
// v0.1.0 project name, so they can be recreated under projectName. Only the
// fixed Core container names are touched; other containers of a "deckplane"
// project (Deckplane Cloud) are left alone. Data lives in volumes and stays.
func releaseLegacyContainers() error {
	for _, name := range []string{containerName, dbContainer, traefikName} {
		if docker.ContainerProject(name) != legacyProject {
			continue
		}
		if err := docker.RemoveContainer(name); err != nil {
			return err
		}
	}
	return nil
}

func writeCompose(dir string, s Settings) error {
	for _, name := range legacyComposeFiles {
		old := filepath.Join(dir, name)
		if _, err := os.Stat(old); err == nil {
			if err := os.Rename(old, old+".old"); err != nil {
				return err
			}
			ui.Info("Moved the old %s aside (now %s.old)", name, name)
		}
	}
	var b bytes.Buffer
	if err := composeTemplate.Execute(&b, s); err != nil {
		return err
	}
	return stack.WriteFile(filepath.Join(dir, composeFile), b.String())
}
