// Package agent installs and manages the Deckplane agent, which connects a
// Docker host to Deckplane Core. The agent image is public, so no registry
// sign-in is needed.
package agent

import (
	"fmt"
	"net/http"
	"net/url"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"text/template"
	"time"

	"github.com/deckplane/cli/internal/docker"
	"github.com/deckplane/cli/internal/envfile"
	"github.com/deckplane/cli/internal/paths"
	"github.com/deckplane/cli/internal/stack"
	"github.com/deckplane/cli/internal/ui"
)

const (
	imageRepo     = "ghcr.io/deckplane/deckplane-agent"
	containerName = "deckplane-agent"
	envFileName   = ".env"
	composeFile   = "compose.yaml"
)

var composeTemplate = template.Must(template.New("agent").Parse(`# Generated by the Deckplane CLI. Do not edit: this file is rewritten by
# "deckplane agent install" and "deckplane agent update". Put your own
# changes in compose.override.yaml next to this file.
name: deckplane-agent

services:
  agent:
    image: {{.}}
    container_name: ` + containerName + `
    restart: unless-stopped
    pid: host
    privileged: true
    env_file: .env
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
      - agent-state:/app/state
    extra_hosts:
      - "host.docker.internal:host-gateway"

volumes:
  agent-state:
`))

// InstallOptions are the flags of `deckplane agent install`.
type InstallOptions struct {
	Dir       string
	ServerURL string
	Token     string
	Name      string
	Version   string
	Yes       bool
	Verbose   bool
}

// Install connects this Docker host to Deckplane Core.
func Install(o InstallOptions) error {
	interactive := ui.Interactive() && !o.Yes
	ui.Title("Deckplane agent installer")

	ui.Step("Checking Docker")
	if err := docker.Check(); err != nil {
		return err
	}
	if err := docker.CheckCompose(); err != nil {
		return err
	}
	ui.Success("Docker %s with Compose is ready", docker.Version())

	if err := paths.EnsureWritable(o.Dir); err != nil {
		hint := "Choose another folder with --dir."
		if !paths.IsRoot() && strings.HasPrefix(o.Dir, "/var/") {
			hint = "Run the command with sudo:  sudo deckplane agent install\n" + hint
		}
		return ui.NewError("Cannot write to "+o.Dir, hint, err)
	}
	envPath := filepath.Join(o.Dir, envFileName)
	env, err := envfile.Load(envPath)
	if os.IsNotExist(err) {
		env = envfile.New(envPath)
		env.Comment("Deckplane agent settings, written by the deckplane CLI.")
	} else if err != nil {
		return err
	}

	serverURL, token := o.ServerURL, o.Token
	if serverURL == "" {
		serverURL = env.Get("CONTROL_PLANE_URL")
	}
	if token == "" {
		token = env.Get("BOOTSTRAP_TOKEN")
	}
	if serverURL == "" || token == "" {
		localURL, localToken := localCore()
		if localURL != "" {
			use := !interactive
			if interactive {
				if use, err = ui.Confirm("Deckplane Core runs on this machine. Connect the agent to it?", true); err != nil {
					return err
				}
			}
			if use {
				serverURL, token = firstNonEmpty(serverURL, localURL), firstNonEmpty(token, localToken)
			}
		}
	}
	if serverURL == "" {
		if !interactive {
			return ui.NewError("The Deckplane Core address is required", "Pass it with --server-url https://deckplane.example.com", nil)
		}
		if serverURL, err = ui.AskRequired("Deckplane Core address (e.g. http://10.0.0.5:3000):", "", validateURL); err != nil {
			return err
		}
	}
	if err := validateURL(serverURL); err != nil {
		return ui.NewError("Invalid --server-url", err.Error(), nil)
	}
	if token == "" {
		if !interactive {
			return ui.NewError("The agent token is required",
				"Pass it with --token. On the Core machine, print it with:  deckplane core token", nil)
		}
		ui.Info("On the machine running Core, print the token with: deckplane core token")
		if token, err = ui.AskSecret("Agent token (hidden):", nil); err != nil {
			return err
		}
	}

	if !strings.Contains(serverURL, "host.docker.internal") {
		ui.Step("Checking that %s is reachable", serverURL)
		if err := checkReachable(serverURL); err != nil {
			return err
		}
		ui.Success("Deckplane Core is reachable")
	}

	name := firstNonEmpty(o.Name, env.Get("AGENT_HOSTNAME"))
	if name == "" {
		name, _ = os.Hostname()
	}
	version := firstNonEmpty(o.Version, env.Get("DECKPLANE_AGENT_VERSION"), "latest")

	env.Set("CONTROL_PLANE_URL", serverURL)
	env.Set("BOOTSTRAP_TOKEN", token)
	env.Set("AGENT_HOSTNAME", name)
	env.Set("DECKPLANE_AGENT_VERSION", version)
	env.SetDefault("DOCKER_SOCKET", "/var/run/docker.sock")
	env.SetDefault("NODE_ENV", "production")
	env.SetDefault("LOG_LEVEL", "info")
	if err := env.Save(); err != nil {
		return err
	}
	if err := writeCompose(o.Dir, version); err != nil {
		return err
	}

	p := docker.Project{Dir: o.Dir, Verbose: o.Verbose}
	if err := pullAndStart(p); err != nil {
		return err
	}
	ui.Box(
		ui.Green("The Deckplane agent is running"),
		"",
		"Name:    "+ui.Bold(name),
		"Core:    "+serverURL,
		"",
		"It should appear under Agents within a minute.",
		"If not, check its logs → deckplane agent logs",
	)
	return nil
}

// localCore returns the address and token of a Core installed on this
// machine, as seen from inside the agent container.
func localCore() (string, string) {
	env, err := envfile.Load(filepath.Join(paths.CoreDir(), ".env"))
	if err != nil {
		return "", ""
	}
	if env.Get("DECKPLANE_EXPOSE") == "domain" && env.Get("DECKPLANE_DOMAIN") != "" {
		return "https://" + env.Get("DECKPLANE_DOMAIN"), env.Get("AGENT_BOOTSTRAP_TOKEN")
	}
	port := env.Get("DECKPLANE_PORT")
	if _, err := strconv.Atoi(port); err != nil {
		port = "3000"
	}
	return "http://host.docker.internal:" + port, env.Get("AGENT_BOOTSTRAP_TOKEN")
}

func validateURL(v string) error {
	u, err := url.Parse(v)
	if err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" {
		return fmt.Errorf("enter a full address starting with http:// or https://")
	}
	return nil
}

func checkReachable(serverURL string) error {
	client := &http.Client{Timeout: 10 * time.Second}
	resp, err := client.Get(strings.TrimRight(serverURL, "/") + "/health")
	if err != nil {
		return ui.NewError("Cannot reach Deckplane Core at "+serverURL,
			"Check the address, and that the Core machine's firewall allows this machine to connect.", err)
	}
	resp.Body.Close()
	if resp.StatusCode >= 500 {
		return ui.NewError(fmt.Sprintf("Deckplane Core answered with HTTP %d", resp.StatusCode),
			"Check it on the Core machine with:  deckplane core status", nil)
	}
	return nil
}

func writeCompose(dir, version string) error {
	var b strings.Builder
	if err := composeTemplate.Execute(&b, imageRepo+":"+version); err != nil {
		return err
	}
	return stack.WriteFile(filepath.Join(dir, composeFile), b.String())
}

func pullAndStart(p docker.Project) error {
	ui.Step("Downloading the Deckplane agent")
	if err := p.Stream("pull"); err != nil {
		return ui.NewError("Downloading the agent image failed", "Run `deckplane doctor` to check the connection.", err)
	}
	ui.Step("Starting the agent")
	if err := p.Run("up", "--detach", "--remove-orphans"); err != nil {
		return err
	}
	time.Sleep(3 * time.Second)
	if state := docker.ContainerState(containerName); state != "running" {
		return ui.NewError("The agent stopped right after starting ("+state+")",
			"Last log lines:\n  "+strings.ReplaceAll(docker.Logs(containerName, 20), "\n", "\n  "), nil)
	}
	ui.Success("Agent started")
	return nil
}

func firstNonEmpty(values ...string) string {
	for _, v := range values {
		if v != "" {
			return v
		}
	}
	return ""
}

// Installation is an existing agent install.
type Installation struct {
	Dir     string
	Env     *envfile.File
	Project docker.Project
}

// Open loads the agent install in dir.
func Open(dir string, verbose bool) (*Installation, error) {
	env, err := envfile.Load(filepath.Join(dir, envFileName))
	if os.IsNotExist(err) {
		return nil, ui.NewError("The Deckplane agent is not installed in "+dir,
			"Install it with:  deckplane agent install\nIf it lives in another folder, pass --dir.", nil)
	}
	if err != nil {
		return nil, err
	}
	return &Installation{Dir: dir, Env: env, Project: docker.Project{Dir: dir, Verbose: verbose}}, nil
}

// Status prints the agent's state.
func (in *Installation) Status() error {
	state := docker.ContainerState(containerName)
	colored := ui.Red(state)
	if state == "running" {
		colored = ui.Green(state)
	}
	ui.Title("Deckplane agent")
	ui.Println("  Status:  %s", colored)
	ui.Println("  Name:    %s", in.Env.Get("AGENT_HOSTNAME"))
	ui.Println("  Core:    %s", in.Env.Get("CONTROL_PLANE_URL"))
	if img := docker.ContainerImage(containerName); img != "" {
		ui.Println("  Image:   %s", img)
	}
	ui.Println("  Files:   %s", in.Dir)
	ui.Println("")
	return nil
}

// Logs shows the agent's logs.
func (in *Installation) Logs(tail int, follow bool) error {
	args := []string{"logs", "--tail", fmt.Sprint(tail)}
	if follow {
		args = append(args, "--follow")
	}
	return in.Project.Attach(args...)
}

// Update pulls a newer image (or the given version) and restarts.
func (in *Installation) Update(version string) error {
	if err := docker.Check(); err != nil {
		return err
	}
	version = firstNonEmpty(version, in.Env.Get("DECKPLANE_AGENT_VERSION"), "latest")
	in.Env.Set("DECKPLANE_AGENT_VERSION", version)
	if err := in.Env.Save(); err != nil {
		return err
	}
	if err := writeCompose(in.Dir, version); err != nil {
		return err
	}
	if err := pullAndStart(in.Project); err != nil {
		return err
	}
	ui.Success("The agent is up to date (%s:%s)", imageRepo, version)
	return nil
}

// Uninstall removes the agent. The state volume keeps the agent's identity
// unless removeData is set.
func (in *Installation) Uninstall(removeData bool) error {
	ui.Step("Removing the Deckplane agent")
	args := []string{"down", "--remove-orphans"}
	if removeData {
		args = append(args, "--volumes")
	}
	if err := in.Project.Run(args...); err != nil {
		return err
	}
	if removeData {
		if err := os.RemoveAll(in.Dir); err != nil {
			return fmt.Errorf("could not remove %s: %w", in.Dir, err)
		}
		ui.Success("The agent and its data were removed")
		return nil
	}
	ui.Success("The agent was removed. Its identity is kept, so reinstalling reconnects it.")
	return nil
}
